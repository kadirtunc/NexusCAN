#[test]
fn every_table_row_matches() {
    let mut failures = Vec::new();
    for &(nbr, dbr, sp, brp, ns1, ns2, nsjw, ds1, ds2, dsjw) in &TABLE {
        let want = (bt(brp, ns1, ns2, nsjw), bt(brp, ds1, ds2, dsjw));
        let got = fd_timing(nbr, dbr, sp);
        if got != Some(want) || data_timing(nbr, dbr, sp) != Some(want.1) {
            failures.push(format!("{nbr}/{dbr} @{sp}: want {want:?}, got {got:?}"));
        }
    }
    assert!(
        failures.is_empty(),
        "{} / {} rows differ:\n{}",
        failures.len(),
        TABLE.len(),
        failures.join("\n")
    );
}

fn rate(brp: u16, seg1: u16, seg2: u16) -> u32 {
    let tq = u32::from(brp) * (1 + u32::from(seg1) + u32::from(seg2));
    (f64::from(CAN_CLOCK_HZ) / f64::from(tq)).round() as u32
}

